#!/usr/bin/env python3
"""variants.json as Rust, for the engine (ports/rosapps/micropolis-engine/src/variants.rs).

    make_variants_rs.py > ../../rosapps/micropolis-engine/src/variants.rs
"""
import json
import os

v = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'variants.json')))
r = {x['name']: x for x in v['rules']}
w, c = r['woods'], r['coast-blob']
assert w['replaces'] == [37] and len(w['variants']) == 3 and len(c['table']) == 256


def mask(name, tiles):
    bits = [0] * 1024
    for t in tiles:
        bits[t] = 1
    words = [sum(bits[i * 64 + k] << k for k in range(64)) for i in range(16)]
    return 'const %s: [u64; 16] = [\n%s];\n' % (name, ''.join('    0x%016x,\n' % x for x in words))


print('// variants.rs -- generated by ports/micropolis/tiles-hd/make_variants_rs.py from')
print('// variants.json: which of the fine tiles\' variants (960 up) to draw in place')
print('// of a map tile, from its position and its neighbours.  Do not edit.')
print()
print('pub const WOODS: u16 = 37;')
print('pub const WOODS_VARIANTS: [u16; 3] = %s;' % w['variants'])
print(mask('COAST_REPLACES', c['replaces']).replace('const', 'pub const'))
print(mask('WATER_SET', c['water_set']).replace('const', 'pub const'))
print(mask('STRUCTURES', c['structures']).replace('const', 'pub const'))
print('pub const COAST_TABLE: [u16; 256] = [\n%s];' % ''.join(
    '    %s,\n' % ', '.join(str(t) for t in c['table'][i:i + 16]) for i in range(0, 256, 16)))
print('''
pub fn has(set: &[u64; 16], t: u16) -> bool {
    let t = (t & 1023) as usize;
    set[t >> 6] >> (t & 63) & 1 != 0
}

/// the hash variants.json chooses woods by
pub fn hash(x: i32, y: i32) -> u32 {
    let mut h = ((x as u32).wrapping_mul(73856093)) ^ ((y as u32).wrapping_mul(19349663));
    h ^= h >> 13;
    h = h.wrapping_mul(0x5BD1E995);
    h ^= h >> 15;
    h
}''')
